"""Registry -> problem folders on main: problem.md, main.py stubs, ✅ status.

The registries on OP are the source of truth; every problem.md is generated
from them, so it can be regenerated at will (render_problems.py) or right after
a scrape. Two kinds of file are never overwritten:

  * a problem.md without the generated marker (or the legacy heading) is
    hand-written, and
  * a main.py that is not an untouched stub is the student's work.

`recommended/` is authored content and is never written.
"""

from __future__ import annotations

import json
import os
import re
import sys
from dataclasses import dataclass, field
from typing import Any, Iterable, Mapping

from . import code, config, fsio, paths

GENERATED_MARKER = (
    "<!-- generated by .op/scripts/render_problems.py from "
    "data/all_problems_detail.json — edit the data, not this file -->"
)
# Heading every problem.md written by the old scraper carries.
LEGACY_HEADING = "## 1. โจทย์จริงจาก iJudge"

PASSED_SUFFIX = " ✅"

CATEGORY_LABELS = (
    ("is_learning_log", "Learning Log"),
    ("is_recommended", "Recommended"),
    ("is_midterm", "Midterm"),
    ("is_mini_exam", "Mini Exam"),
)


