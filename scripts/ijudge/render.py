def _is_under(path: str, root: str) -> bool:
    return os.path.normpath(os.path.dirname(path)) == os.path.normpath(root)


def target_folder(item: Mapping[str, Any], index: Mapping[int, str] | None = None) -> str:
    """Folder of a problem on main: the existing one, else where a new one goes.

    `index` is a precomputed paths.index_problem_dirs() for batch callers.
    """
    pid = int(item["id"])
    existing = (index if index is not None else paths.index_problem_dirs()).get(pid)
    if existing:
        return existing
    if item.get("is_learning_log"):
        return os.path.join(paths.MAIN_ROOT, f"oj{pid}")
    name = config.folder_name(pid, item.get("name"))
    if item.get("status") == "Passed":
        name += PASSED_SUFFIX
    return os.path.join(paths.OJ_DIR, name)


def status_folder(item: Mapping[str, Any], folder: str) -> str:
    """Path `folder` should have for the problem's pass status.

    Only folders directly under oj/ carry the ✅ suffix; Learning Log folders
    at the root keep their name whatever the status.
    """
    if not _is_under(folder, paths.OJ_DIR):
        return folder
    base = re.sub(r"\s*✅$", "", os.path.basename(folder))
    if item.get("status") == "Passed":
        base += PASSED_SUFFIX
    return os.path.join(paths.OJ_DIR, base)


def sync_folder_status(item: Mapping[str, Any], folder: str) -> str:
    """Add or remove the ✅ suffix of an oj/ folder to match its status.

    Returns the folder's path afterwards: unchanged under --dry-run or when
    the rename is refused because the target exists.
    """
    desired = status_folder(item, folder)
    if desired == folder:
        return folder
    if fsio.rename_dir(folder, desired) and not fsio.is_dry_run():
        return desired
    return folder


