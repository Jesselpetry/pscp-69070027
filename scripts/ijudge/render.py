def _sample_text(value: Any) -> str:
    """Sample I/O exactly as judged: only line endings and outer blank lines.

    Leading spaces are kept, since pattern-drawing outputs depend on them.
    """
    if value is None:
        return ""
    text = str(value).replace("\r\n", "\n").replace("\r", "\n")
    return text.strip("\n")


def _sample_block(label: str, text: str, empty: str) -> list[str]:
    body = text.split("\n") if text.strip() else [empty]
    return [f"- **{label}**:", "  ```text", *(f"  {line}" for line in body), "  ```"]


def _week_line(item: Mapping[str, Any]) -> str | None:
    """'Week 10 · Learning Log' for the quote block, or None if unknown."""
    week = item.get("week")
    week_text = config.week_label(week) if week is not None else ""
    parts = [week_text] if week_text else []
    for flag, label in CATEGORY_LABELS:
        # "Week 7 / Midterm" already says Midterm.
        if item.get(flag) and label.lower() not in week_text.lower():
            parts.append(label)
    return " · ".join(parts) or None


def render_problem_md(detail: Mapping[str, Any], summary: Mapping[str, Any] | None) -> str:
    """problem.md for one detail record; `summary` supplies title, week, flags.

    The summary registry is preferred for those fields because a --fast scrape
    refreshes it without touching the detail records.
    """
    meta: Mapping[str, Any] = summary or detail
    cp = detail.get("courseProblem") or {}
    prob = detail.get("problem") or {}
    samples = detail.get("sampleCases") or []

    pid = detail.get("id") or cp.get("cp_id") or meta.get("id")
    raw_title = meta.get("name") or cp.get("cp_title") or prob.get("problem_title")
    title = config.clean_title(raw_title) or f"OJ {pid}"
    timeout = cp.get("cp_timeout") or 1
    memory_limit = cp.get("cp_memory_limit") or 32000
    lang = cp.get("cp_lang_type") or "Python"
    note = re.sub(r"\s*\n\s*", " ", normalize_statement(prob.get("problem_note")))

    def section(key: str) -> str:
        return _hard_breaks(normalize_statement(prob.get(key)))

    desc = section("problem_description")
    input_spec = section("problem_input_specification")
    output_spec = section("problem_output_specification")

    lines = [
        GENERATED_MARKER,
        f"# OJ {pid}: {title}",
        "",
        f"> - **iJudge cp_id**: {pid} — ภาษา {lang}",
        f"> - **เวลาจำกัด**: {timeout} วินาที | **หน่วยความจำ**: {memory_limit:,} KB",
    ]
    week_line = _week_line(meta)
    if week_line:
        lines.append(f"> - **สัปดาห์**: {week_line}")
    if note:
        lines.append(f"> - **โน้ตจากผู้ออกโจทย์**: {note}")
    lines += [
        "",
        "---",
        "",
        LEGACY_HEADING,
        "",
        desc or "*(ไม่มีคำอธิบายเพิ่มเติม)*",
        "",
        "## 2. Input Specification",
        "",
        input_spec or "*(ไม่มีข้อกำหนดอินพุต)*",
        "",
        "## 3. Output Specification",
        "",
        output_spec or "*(ไม่มีข้อกำหนดเอาต์พุต)*",
        "",
        "## 4. ตัวอย่างจาก iJudge",
        "",
    ]
    if samples:
        for idx, sample in enumerate(samples, 1):
            lines.append(f"### ตัวอย่างที่ {idx}")
            lines += _sample_block("อินพุต", _sample_text(sample.get("testcase_input")),
                                   "(ไม่มีอินพุต)")
            lines += _sample_block("เอาต์พุต", _sample_text(sample.get("testcase_output")),
                                   "(ไม่มีเอาต์พุต)")
            lines.append("")
    else:
        lines += ["*(ไม่มีตัวอย่าง Sample Testcase)*", ""]
    return "\n".join(lines).strip() + "\n"


def is_generated_md(text: str) -> bool:
    """True if a problem.md was written by a script and may be regenerated."""
    return GENERATED_MARKER in text or LEGACY_HEADING in text


def is_untouched_stub(text: str) -> bool:
    """Stricter code.is_stub: the marker alone does not make a file a stub.

    code.is_stub accepts any file containing STUB_MARKER, which would include
    a solution written underneath the marker comment. Before overwriting,
    require the file to still be a stub with the marker removed.
    """
    return code.is_stub(text) and code.is_stub(text.replace(code.STUB_MARKER, ""))


