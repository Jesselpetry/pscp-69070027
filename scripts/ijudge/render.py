# iJudge statements are markdown with raw HTML fragments mixed in. Ported from
# ihelp's build_pscp_registry.normalize_statement, plus the structural tags
# that would otherwise lose meaning when stripped: <pre> keeps its layout as a
# fence, <li> becomes a list item, <a> a markdown link.
_STRUCTURE_REWRITES = [
    (re.compile(r"<pre[^>]*>\n?", re.I), "\n```text\n"),
    (re.compile(r"\n?</pre>", re.I), "\n```\n"),
    (re.compile(r'<a\s[^>]*?href="([^"]*)"[^>]*>(.*?)</a>', re.I),
     lambda m: f"[{m.group(2) or m.group(1)}]({m.group(1)})"),
    (re.compile(r"^[ \t]*<li\b[^>]*>", re.I | re.M), "- "),
    (re.compile(r"<li\b[^>]*>", re.I), "\n- "),
]

def _emphasis(marker: str):
    """Rewrite a paired tag to markdown emphasis with the spaces moved out.

    `<b>บรรทัดที่ 1 : </b>` must become `**บรรทัดที่ 1 :** `: a closing
    `**` right after a space is not a closer, and the bold never ends.
    """
    def repl(m: re.Match[str]) -> str:
        inner = m.group(2)
        core = inner.strip()
        if not core:
            return inner
        lead = inner[: len(inner) - len(inner.lstrip())]
        trail = inner[len(inner.rstrip()):]
        return f"{lead}{marker}{core}{marker}{trail}"
    return repl


_TAG_REWRITES = [
    # `<br />` is usually followed by the source's own newline; together they
    # are one line break, not a paragraph break.
    (re.compile(r"<br\s*/?>[ \t]*\n?", re.I), "\n"),
    (re.compile(r"<(b|strong)>(.*?)</\1>", re.I | re.S), _emphasis("**")),
    (re.compile(r"<(i|em)>(.*?)</\1>", re.I | re.S), _emphasis("*")),
    (re.compile(r"</?(?:u|ins)>", re.I), ""),
    (re.compile(r"</?(?:b|strong)>", re.I), "**"),
    (re.compile(r"</?(?:i|em)>", re.I), "*"),
    (re.compile(r"</?(?:p|div|span|font)[^>]*>", re.I), ""),
]

# Decoded `<` and `>` go through placeholders so the escaping pass can tell
# them apart from HTML that is kept on purpose (<img>, <!-- -->).
_LT, _GT = "", ""
_ENTITIES = {
    "&nbsp;": " ", "&amp;": "&", "&lt;": _LT, "&gt;": _GT, "&quot;": '"',
    "&#39;": "'",
}

_FENCE_OPEN = re.compile(r"^ {0,3}(`{3,}|~{3,})")
_CODE_SPAN = re.compile(r"(?<!`)(`+)(?!`)(.+?)(?<!`)\1(?!`)")


def _split_fences(text: str) -> list[tuple[bool, list[str]]]:
    """Split markdown into (is_fenced_code, lines) runs.

    An unclosed fence runs to the end of the text, as in CommonMark.
    """
    runs: list[tuple[bool, list[str]]] = []
    current: list[str] = []
    fence: str | None = None
    for line in text.split("\n"):
        if fence is None:
            m = _FENCE_OPEN.match(line)
            if m:
                if current:
                    runs.append((False, current))
                current, fence = [line], m.group(1)
                continue
            current.append(line)
        else:
            current.append(line)
            stripped = line.strip()
            if stripped and set(stripped) == {fence[0]} and len(stripped) >= len(fence):
                runs.append((True, current))
                current, fence = [], None
    if current:
        runs.append((fence is not None, current))
    return runs


def _escape_prose(text: str, line_start: bool) -> str:
    """Escape what GitHub would misread in plain statement text."""
    # `$` starts LaTeX math on GitHub (problem 3362 prints `$` symbols).
    text = re.sub(r"(?<!\\)\$", r"\\$", text)
    # A decoded `<type>` would be swallowed as an unknown HTML tag.
    text = re.sub(_LT + r"(?=[A-Za-z/!?])", r"\\<", text)
    # A decoded `>` opening a line would start a block quote.
    if line_start:
        text = re.sub(r"^(\s*)" + _GT, r"\1\\>", text)
    return text.replace(_LT, "<").replace(_GT, ">")


def _escape_markdown(text: str) -> str:
    """Apply _escape_prose outside fenced code and inline code spans."""
    out: list[str] = []
    for fenced, lines in _split_fences(text):
        for line in lines:
            if fenced:
                out.append(line.replace(_LT, "<").replace(_GT, ">"))
                continue
            parts: list[str] = []
            last = 0
            for m in _CODE_SPAN.finditer(line):
                parts.append(_escape_prose(line[last:m.start()], last == 0))
                parts.append(m.group(0).replace(_LT, "<").replace(_GT, ">"))
                last = m.end()
            parts.append(_escape_prose(line[last:], last == 0))
            out.append("".join(parts))
    return "\n".join(out)


def normalize_statement(text: str | None) -> str:
    """iJudge statement HTML/markdown -> clean GitHub markdown.

    Unknown tags are dropped before entities are decoded: decoding first
    turns text such as `&lt; หรือ &lt;= หรือ &gt;` (3354) into something
    that looks like a tag and deletes it. Markdown image links are untouched.
    """
    if not text:
        return ""
    out = text.replace("\r\n", "\n").replace("\r", "\n")
    for pattern, repl in _STRUCTURE_REWRITES + _TAG_REWRITES:
        out = pattern.sub(repl, out)
    # Any tag we did not plan for is dropped rather than rendered literally.
    out = re.sub(r"<[^>\n]{1,40}>", "", out)
    for entity, repl in _ENTITIES.items():
        out = out.replace(entity, repl)
    # Collapse the runs of blank lines the <br /> expansion can leave behind.
    out = re.sub(r"\n{3,}", "\n\n", out)
    return _escape_markdown(out.strip())


def _hard_breaks(text: str) -> str:
    """Keep iJudge's line breaks when GitHub renders the text.

    iJudge shows every newline as a break (and `<br />` became one above);
    GitHub joins single newlines into one line. Two trailing spaces mark a
    hard break, and are simply dropped at the end of a block.
    """
    out: list[str] = []
    for fenced, lines in _split_fences(text):
        if fenced:
            out.extend(lines)
            continue
        lines = [line.rstrip() for line in lines]
        for i, line in enumerate(lines):
            following = lines[i + 1] if i + 1 < len(lines) else ""
            out.append(f"{line}  " if line and following else line)
    return "\n".join(out)


