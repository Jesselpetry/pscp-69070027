@dataclass
class RenderStats:
    problem_md_written: int = 0
    folders_created: int = 0
    folders_renamed: int = 0
    stubs_created: int = 0
    stubs_refreshed: int = 0
    stubs_seeded: int = 0
    handwritten_skipped: list[int] = field(default_factory=list)
    no_detail: list[int] = field(default_factory=list)

    @property
    def changes(self) -> int:
        return (self.problem_md_written + self.folders_created + self.folders_renamed
                + self.stubs_created + self.stubs_refreshed + self.stubs_seeded)

    def report(self) -> str:
        lines = [
            f"problem.md written:    {self.problem_md_written}",
            f"folders created:       {self.folders_created}",
            f"folders renamed (✅):   {self.folders_renamed}",
            f"main.py stubs created: {self.stubs_created}",
            f"stubs refreshed:       {self.stubs_refreshed}",
            f"stubs seeded:          {self.stubs_seeded}",
            f"hand-written skipped:  {len(self.handwritten_skipped)}"
            + (f" ({', '.join(map(str, self.handwritten_skipped))})"
               if self.handwritten_skipped else ""),
        ]
        if self.no_detail:
            lines.append("no detail record (problem.md left alone): "
                         + ", ".join(map(str, self.no_detail)))
        return "\n".join(lines)


def load_registry(path: str) -> dict[int, dict[str, Any]]:
    """A registry JSON file as {id: record}; empty if it does not exist."""
    if not os.path.exists(path):
        return {}
    with open(path, "r", encoding="utf-8") as f:
        return {int(rec["id"]): rec for rec in json.load(f)}


def _read(path: str) -> str | None:
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        return f.read()


def _render_main_py(item: Mapping[str, Any], detail: Mapping[str, Any] | None,
                    folder: str, seed_code: bool, stats: RenderStats) -> None:
    path = os.path.join(folder, "main.py")
    stub = code.stub_solution(config.clean_title(item.get("name")))
    seed = (detail or {}).get("beforeCode") if seed_code else None
    if not isinstance(seed, str) or not seed.strip():
        seed = None

    existing = _read(path)
    if existing is None:
        fsio.write_text(path, seed or stub)
        if seed:
            stats.stubs_seeded += 1
        else:
            stats.stubs_created += 1
        return
    if not is_untouched_stub(existing):
        return
    if seed and existing != seed:
        fsio.write_text(path, seed)
        stats.stubs_seeded += 1
    elif not seed and existing != stub:
        fsio.write_text(path, stub)
        stats.stubs_refreshed += 1


def render_problem(item: Mapping[str, Any], detail: Mapping[str, Any] | None,
                   *, seed_code: bool = False, stats: RenderStats | None = None,
                   index: Mapping[int, str] | None = None) -> RenderStats:
    """Bring one problem's folder on main in line with the registries."""
    stats = stats if stats is not None else RenderStats()
    pid = int(item["id"])
    folder = target_folder(item, index)
    if os.path.abspath(folder).startswith(os.path.abspath(paths.RECOMMENDED_DIR) + os.sep):
        print(f"[SKIP] oj{pid}: refusing to write into recommended/", file=sys.stderr)
        return stats

    if os.path.isdir(folder):
        desired = status_folder(item, folder)
        if desired != folder and not os.path.exists(desired):
            folder = sync_folder_status(item, folder)
            stats.folders_renamed += 1
        elif desired != folder:
            sync_folder_status(item, folder)  # reports the refusal
    else:
        fsio.ensure_dir(folder)
        stats.folders_created += 1

    md_path = os.path.join(folder, "problem.md")
    if detail is None:
        stats.no_detail.append(pid)
    else:
        fresh = render_problem_md(detail, item)
        current = _read(md_path)
        if current is not None and not is_generated_md(current):
            stats.handwritten_skipped.append(pid)
        elif current != fresh:
            fsio.write_text(md_path, fresh)
            stats.problem_md_written += 1

    _render_main_py(item, detail, folder, seed_code, stats)
    return stats


def render_ids(
    ids: Iterable[int] | None = None,
    *,
    seed_code: bool = False,
    summaries: Mapping[int, Mapping[str, Any]] | None = None,
    details: Mapping[int, Mapping[str, Any]] | None = None,
) -> RenderStats:
    """Render the given problem ids (default: every summary record).

    The registries are read from data/ unless passed in; the scraper passes
    its in-memory copies so a --dry-run scrape previews the fetched data.
    """
    summaries = summaries if summaries is not None else load_registry(paths.SUMMARY_JSON)
    details = details if details is not None else load_registry(paths.DETAIL_JSON)
    wanted = sorted(summaries) if ids is None else sorted(set(ids))

    stats = RenderStats()
    index = paths.index_problem_dirs()
    for pid in wanted:
        item = summaries.get(pid) or details.get(pid)
        if item is None:
            print(f"[WARN] oj{pid}: not in the registries, skipped", file=sys.stderr)
            continue
        render_problem(item, details.get(pid), seed_code=seed_code, stats=stats, index=index)
    return stats


def parse_ids(raw: str) -> set[int]:
    """Parse an id selection such as '3226,3290-3301'. Raises ValueError."""
    ids: set[int] = set()
    for token in raw.split(","):
        token = token.strip()
        if not token:
            continue
        if "-" in token:
            start, end = token.split("-", 1)
            ids.update(range(int(start), int(end) + 1))
        else:
            ids.add(int(token))
    return ids
